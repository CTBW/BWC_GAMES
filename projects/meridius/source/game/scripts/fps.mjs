import { chromium } from 'playwright-core';
const exe = process.env.CHROME_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const browser = await chromium.launch({ executablePath: exe, headless: false, args: ['--window-size=1920,1080'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.addInitScript(() => localStorage.setItem('meridius.manual.seen', '1'));
await page.goto('http://localhost:5199/?newgame&seed=5');
await page.waitForFunction(() => window.__meridius?.store?.screen === 'base');
await page.waitForTimeout(2500);
const base = await page.evaluate(() => window.__meridius.engine.fps);
await page.evaluate(() => window.__meridius.store.debug.testBattle('warband_camp', { mapId: 'goblin_camp', seed: 5 }));
await page.waitForTimeout(3500);
const battle = await page.evaluate(() => window.__meridius.engine.fps);
await page.evaluate(() => window.__meridius.store.debug.autoPrepare(2));
await page.waitForTimeout(3500);
const camp = await page.evaluate(() => window.__meridius.engine.fps);
console.log(JSON.stringify({ base: base.toFixed(1), battle: battle.toFixed(1), campaign: camp.toFixed(1) }));
await browser.close();
