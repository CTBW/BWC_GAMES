"""Build audition.html in the audio library: every candidate take with a player,
Like/Reject buttons and a note, saved as picks.json by the owner.

  python -I tools/audio/make_audition.py [library_dir]

Library: the argument, else $MERIDIUS_AUDIO_LIBRARY, else local/audio-library at
the repository root (gitignored).
Reads candidates.json (the owner's verdicts are its owner_verdict/owner_note,
the game's use its integrated_in) and the round-1 voice files in
voices/higgsfield/; the page is audition_template.html (next to this script)
with the take list filled in. Voice takes generated by tools/audio/hfvoice.py
are listed per round and per the event their line is for.
"""
import json
import os
import re
import sys
from urllib.parse import quote

HERE = os.path.dirname(os.path.abspath(__file__))
# The repository's gitignored local/ folder (local/README.md).
DEFAULT_LIBRARY = os.path.join(HERE, "..", "..", "..", "..", "..", "..", "local", "audio-library")
lib = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("MERIDIUS_AUDIO_LIBRARY", DEFAULT_LIBRARY))
cands = json.load(open(os.path.join(lib, "candidates.json"), encoding="utf-8"))
events = cands.get("events", cands)

GROUPS = [
    ("Steel: swords clashing", ["sword_clash", "sword_swing", "sword_shield_metal", "sword_shield_wood", "blade_armor", "blade_flesh", "parry_block", "miss_whoosh", "spear_thrust", "melee_bed"]),
    ("Fireball", ["fire_cast", "fire_whoosh", "fire_loop", "fire_explosion"]),
    ("Camp: forest and birds", ["forest_day_bed", "campfire", "bird_chaffinch", "bird_blackbird", "bird_robin", "bird_wren", "bird_great_tit", "bird_cuckoo", "bird_wood_pigeon", "bird_raven_crow", "wood_chop", "camp_murmur"]),
    ("Boots and armour", ["boot_step_dirt", "boot_step_grass", "armor_jingle", "march_group"]),
    ("Trolls", ["troll_stomp", "log_smash", "troll_roar", "troll_grunt_breath"]),
    ("Wolves and collies", ["wolf_growl", "wolf_howl", "wolf_bark_yelp", "wolf_paws", "dog_growl", "dog_bark", "dog_whimper", "dog_lap", "dog_paws"]),
    ("Orcs, goblins, men", ["orc_growl", "club_smash", "goblin_vocal", "goblin_feet", "male_attack_grunt", "male_pain", "male_death"]),
    ("Magic", ["lightning_crack", "thunder", "ice_frost", "heal_shimmer", "dark_curse"]),
    ("Bows and war engines", ["bow_release", "crossbow_shot", "arrow_whiz", "arrow_impact_wood", "arrow_impact_flesh_shield", "ballista", "catapult", "siege_creak", "boulder_impact", "cart_rumble", "cart_crash"]),
    ("Battle and night ambience", ["wind_open_field", "night_crickets", "owl_tawny"]),
    ("Horns and drums", ["war_horn", "goblin_horn", "war_drums"]),
    ("UI", ["ui_page_turn", "ui_click", "ui_coins", "ui_building"]),
]
VOICE_CATS = {"voice_commander": "commander", "voice_cheer": "victory cheer", "voice_goblin": "goblin",
              "voice_orc_warcry": "orc war cry"}
listed = {e for _, evs in GROUPS for e in evs} | set(VOICE_CATS)
rest = [e for e in events if e not in listed]
if rest:
    GROUPS.append(("Other", rest))


def rel_url(path):
    rel = os.path.relpath(path, lib)
    return "/".join(quote(p) for p in rel.split(os.sep))


def take(t):
    src = t.get("source") or ""
    edited = "pitched edit" in src or src.endswith("filtered")
    return {
        "id": t.get("id"),
        "url": rel_url(t["file"]),
        "kind": "pitched" if edited else t.get("kind"),
        "source": src,
        "license": (t.get("license") or "").split("(")[0].strip(),
        "dur": t.get("duration_s"),
        "notes": re.sub(r"\s*\[for: [^\]]*\]$", "", t.get("notes") or ""),
        "page": t.get("url"),
        "ingame": ", ".join(t.get("integrated_in") or []),
        "verdict": t.get("owner_verdict") or "",
        "vnote": t.get("owner_note") or "",
    }


def purpose(t):
    m = re.search(r"\[for: ([^\]]*)\]$", t.get("notes") or "")
    return m.group(1) if m else ""


groups = []
for title, evs in GROUPS:
    g = {"title": title, "badge": "", "events": []}
    for e in evs:
        if e in events and events[e]:
            g["events"].append({"event": e, "takes": [take(t) for t in events[e]]})
    if g["events"]:
        groups.append(g)

# Voices: hfvoice.py rounds (newest first), split by what each line is for; then round 1's casting.
by_round = {}
in_candidates = set()
for cat, label in VOICE_CATS.items():
    for t in events.get(cat, []):
        in_candidates.add(os.path.normcase(os.path.normpath(t["file"])))
        m = re.match(r"hf_(round\d+)_", t["id"])
        rnd = m.group(1) if m else "round1"
        key = label + (": " + purpose(t) if purpose(t) else "")
        by_round.setdefault(rnd, {}).setdefault(key, []).append(take(t))

# Round-1 files not in candidates.json (the casting takes not chosen), with the verdicts given on 24 Oct.
VOICE_VERDICT = {
    "11_goblin_benji": ("rejected", "none of the goblins"), "12_goblin_archie": ("rejected", "none of the goblins"),
}
vdir = os.path.join(lib, "voices", "higgsfield")
receipts = json.load(open(os.path.join(vdir, "receipts.json"), encoding="utf-8"))
by_index = {j["index"]: j for j in receipts["round1"]["jobs"]}
for sub, kind in (("round1", "original"), ("round1_derived", "pitched")):
    d = os.path.join(vdir, sub)
    for f in sorted(os.listdir(d)):
        p = os.path.join(d, f)
        if not f.endswith((".mp3", ".wav")) or os.path.normcase(os.path.normpath(p)) in in_candidates:
            continue
        j = by_index.get(int(f.split("_")[0]), {})
        role = {"commander": "commander", "orc": "orc war cry", "goblin": "goblin"}.get(j.get("role"), "voice")
        stem = os.path.splitext(f)[0]
        by_round.setdefault("round1", {}).setdefault(role, []).append({
            "id": stem, "url": rel_url(p), "kind": kind,
            "source": "Higgsfield Eleven v4, voice %s, job %s" % (j.get("voice"), j.get("job_id")),
            "license": "Higgsfield output", "dur": None,
            "notes": ("Pitched edit: " if kind == "pitched" else "") + (j.get("text") or ""), "page": None,
            "verdict": VOICE_VERDICT.get(stem, ("", ""))[0], "vnote": VOICE_VERDICT.get(stem, ("", ""))[1], "ingame": "",
        })

voice_groups = []
for rnd in sorted(by_round, key=lambda r: -int(r[5:])):
    date = receipts.get(rnd, {}).get("submitted", "")
    new = rnd != "round1"
    voice_groups.append({
        "title": "Voices, %s%s" % ("round " + rnd[5:], " (%s)" % date if date else ""),
        "badge": "new" if new else "",
        # Lines the game can play now first, then those that wait for a hook.
        "events": [{"event": k, "takes": v} for k, v in sorted(by_round[rnd].items(), key=lambda kv: ("needs a hook" in kv[0], kv[0]))],
    })
groups = voice_groups + groups

data = json.dumps(groups, ensure_ascii=False).replace("</", "<\\/")
tpl = open(os.path.join(HERE, "audition_template.html"), encoding="utf-8").read()
out = os.path.join(lib, "audition.html")
with open(out, "w", encoding="utf-8") as f:
    f.write(tpl.replace("/*DATA*/[]", data))
n = sum(len(e["takes"]) for g in groups for e in g["events"])
todo = sum(1 for g in groups for e in g["events"] for t in e["takes"] if not t["verdict"])
print(out, n, "takes,", todo, "without a verdict")
