/** Abilities a squad uses from its panel: stances, shouts, spells and attack abilities with their own damage. */
export function isActiveAbility(id: string): boolean {
  const ab = ABILITIES[id];
  return !!ab && (ab.kind !== 'attack' || !!ab.damageMult);
}
